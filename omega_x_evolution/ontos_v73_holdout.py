"""One-shot blind binary holdout contract, operated by a trusted broker.

No candidate code runs here. Authentication does not prove that predictions
were generated by the declared artifact. Process isolation and persistent
campaign uniqueness are responsibilities of the enclosing trusted service.
"""
from __future__ import annotations

from dataclasses import dataclass
import hashlib
import re
from threading import Lock

from .ontos_v72_jcs import canonical_json, parse_json
from .ontos_v72_receipts import _prime_order_point, strict_verify

_ID = re.compile(r'[A-Za-z0-9][A-Za-z0-9._-]{0,63}\Z', re.ASCII)
_HEX = re.compile(r'[0-9a-f]{64}\Z', re.ASCII)
_MAX_ROWS = 4096
_MAX_CANDIDATES = 64
_DOMAIN = b'OMEGA-X/v73/holdout/'


def _id(value: object) -> bool:
    return type(value) is str and _ID.fullmatch(value) is not None


def _digest(value: object) -> bool:
    return type(value) is str and _HEX.fullmatch(value) is not None


def _predictions(values: object) -> bool:
    return (type(values) is tuple and 1 <= len(values) <= _MAX_ROWS
            and all(x is None or type(x) is int and x in (0, 1) for x in values))


def label_commitment(truth: tuple[int, ...], salt: bytes) -> str:
    """Commit to ordered private labels using an independently secret salt."""
    if (not _predictions(truth) or any(x is None for x in truth)
            or type(salt) is not bytes or len(salt) != 32):
        raise ValueError('bounded binary truth and 32-byte salt required')
    return hashlib.sha256(_DOMAIN + b'labels\x00' + salt + bytes(truth)).hexdigest()


@dataclass(frozen=True, slots=True)
class Candidate:
    name: str
    artifact_sha256: str
    public_key: bytes

    def __post_init__(self) -> None:
        if (not _id(self.name) or not _digest(self.artifact_sha256)
                or not _prime_order_point(self.public_key)):
            raise ValueError('invalid candidate manifest')


@dataclass(frozen=True, slots=True)
class HoldoutPlan:
    tenant: str
    campaign: str
    protocol_sha256: str
    features_sha256: str
    rows: int
    labels_commitment: str
    candidates: tuple[Candidate, ...]
    external_key: bytes

    def __post_init__(self) -> None:
        if (not _id(self.tenant) or not _id(self.campaign)
                or not all(_digest(x) for x in (self.protocol_sha256,
                    self.features_sha256, self.labels_commitment))
                or type(self.rows) is not int or not 1 <= self.rows <= _MAX_ROWS
                or type(self.candidates) is not tuple
                or not 1 <= len(self.candidates) <= _MAX_CANDIDATES
                or any(type(c) is not Candidate for c in self.candidates)
                or not _prime_order_point(self.external_key)):
            raise ValueError('invalid holdout manifest')
        for candidate in self.candidates:
            candidate.__post_init__()
        names = {c.name for c in self.candidates}
        keys = {c.public_key for c in self.candidates}
        if (len(names) != len(self.candidates) or len(keys) != len(self.candidates)
                or self.external_key in keys):
            raise ValueError('candidate and external authority must be distinct')

    def body(self) -> dict:
        self.__post_init__()
        return {'schema':'omega-v73-binary-holdout-v1','tenant':self.tenant,
                'campaign':self.campaign,'protocol_sha256':self.protocol_sha256,
                'features_sha256':self.features_sha256,'rows':self.rows,
                'labels_commitment':self.labels_commitment,
                'external_key':self.external_key.hex(),
                'candidates':[{'name':c.name,'artifact_sha256':c.artifact_sha256,
                               'public_key':c.public_key.hex()}
                              for c in sorted(self.candidates,key=lambda c:c.name)]}


def submission_bytes(plan_digest: str, candidate: str,
                     values: tuple[int | None, ...]) -> bytes:
    if not _digest(plan_digest) or not _id(candidate) or not _predictions(values):
        raise ValueError('invalid signed submission')
    return _DOMAIN + b'submit\x00' + canonical_json(
        {'plan':plan_digest,'candidate':candidate,'predictions':list(values)})


def seal_bytes(plan_digest: str) -> bytes:
    if not _digest(plan_digest):
        raise ValueError('invalid plan digest')
    return _DOMAIN + b'seal\x00' + bytes.fromhex(plan_digest)


class HoldoutBroker:
    """Immutable plan and single submission per candidate; no intermediate scores."""

    def __init__(self, plan: HoldoutPlan, truth: tuple[int, ...], salt: bytes) -> None:
        if type(plan) is not HoldoutPlan:
            raise ValueError('typed plan required')
        body = plan.body()
        if label_commitment(truth,salt) != plan.labels_commitment or len(truth) != plan.rows:
            raise ValueError('label commitment mismatch')
        self._plan_digest = hashlib.sha256(canonical_json(body)).hexdigest()
        self._rows = plan.rows
        self._keys = {c.name:c.public_key for c in plan.candidates}
        self._external_key = plan.external_key
        self._truth = truth
        self._submissions: dict[str, tuple[int | None, ...]] = {}
        self._sealed: bytes | None = None
        self._lock = Lock()

    @property
    def plan_digest(self) -> str:
        return self._plan_digest

    def submit(self, candidate: str, values: tuple[int | None, ...], signature: bytes) -> str:
        if not _id(candidate) or not _predictions(values) or len(values) != self._rows:
            return 'REJECTED'
        with self._lock:
            key = self._keys.get(candidate)
            if self._sealed is not None or key is None or candidate in self._submissions:
                return 'REJECTED'
            if not strict_verify(key,submission_bytes(self._plan_digest,candidate,values),signature):
                return 'REJECTED'
            self._submissions[candidate] = values
            return 'ACCEPTED'

    def seal(self, signature: bytes) -> str:
        """Trusted authority closes all candidates together; absent rows remain failures."""
        with self._lock:
            if not strict_verify(self._external_key,seal_bytes(self._plan_digest),signature):
                return 'REJECTED'
            if self._sealed is None:
                results = {}
                for name in sorted(self._keys):
                    values = self._submissions.get(name)
                    correct = incorrect = 0
                    if values is not None:
                        for prediction, label in zip(values,self._truth):
                            if prediction is not None:
                                correct += int(prediction == label)
                                incorrect += int(prediction != label)
                    results[name] = {'status':'MISSING' if values is None else 'SCORED',
                                     'correct':correct,'incorrect':incorrect,
                                     'abstained':self._rows-correct-incorrect,'total':self._rows}
                self._sealed = canonical_json({'plan_sha256':self._plan_digest,
                    'candidates':results,'release_authorized':False})
                self._truth = ()
                self._submissions.clear()
            return 'SEALED'

    def report(self) -> dict | None:
        with self._lock:
            return None if self._sealed is None else parse_json(self._sealed)
